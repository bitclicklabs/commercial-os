/** One decision being classified: where it was seen and about whom. */
export interface Occurrence {
  traceId: string;
  executionId: string;
  /** 1-based position in the trace's decision order. */
  position: number;
  name: string;
}

/** Rules that cover one occurrence (by trace/position or by entity). */
export function matchExclusions(occ: Occurrence, rules: readonly ExclusionRule[] = EXCLUSION_RULES): ExclusionRule[] {
  const key = entityKeyOf(occ.name);
  return rules.filter((r) => {
    const byTrace = (r.traces ?? []).some(
      (t) =>
        (t.trace_id === occ.traceId || t.execution_id === occ.executionId) &&
        (!t.positions || (occ.position >= t.positions.from && occ.position <= t.positions.to)),
    );
    const byName = (r.names ?? []).some((n) => entityKeyOf(n) === key);
    return byTrace || byName;
  });
}
